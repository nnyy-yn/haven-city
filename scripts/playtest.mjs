async function build(kind){
  const s=await state();
  const cells=[];
  for(let gx=2;gx<22;gx++)for(let gz=3;gz<21;gz++)if(!s.buildings.some(b=>b.gx===gx&&b.gz===gz)&&s.buildings.some(b=>b.kind==='road'&&Math.abs(b.gx-gx)+Math.abs(b.gz-gz)===1))cells.push({gx,gz});
  cells.sort((a,b)=>(a.gx-12)**2+(a.gz-12)**2-((b.gx-12)**2+(b.gz-12)**2));
  const c=cells[0],p=await screen(c.gx,c.gz);
  await page.locator(`[data-tool="${kind}"]`).click();
  await page.mouse.move(p.x,p.y);await page.mouse.click(p.x,p.y);
  const after=await state();
  check(`build ${kind}`,after.buildings.some(b=>b.kind===kind&&b.gx===c.gx&&b.gz===c.gz),c);
  await page.keyboard.press('Escape');
  return {before:s,after,cell:c};
}
